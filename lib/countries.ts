export const countryName = (code: string): string => COUNTRY_NAMES[code] ?? code;

/** Flag emoji from the two regional-indicator symbols. XK (Kosovo) has a flag on most
 *  platforms; anything a platform lacks degrades to the two letters, which is still legible. */
export const countryFlag = (code: string): string =>
  /^[A-Z]{2}$/.test(code)
    ? String.fromCodePoint(...[...code].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65))
    : "";

// Adjective forms for "Vietnamese heritage" on /afarm/track-record cards. Only countries
// used as heritage need one; any other code reads "<country name> heritage".
