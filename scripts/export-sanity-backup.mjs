/**
 * export-sanity-backup.mjs
 * Local, restorable snapshot of the whole Sanity dataset.
 *
 * Writes one JSON file per document type to sanity-backup/ (gitignored), plus a
 * backup-manifest.json with the export timestamp and per-type counts.
 *
 * Run:  node scripts/export-sanity-backup.mjs
 * (Reads are public on this dataset, so no token is required. If a
 *  SANITY_WRITE_TOKEN env var is present it will be used.)
 *
 * ─── WHY THIS DISCOVERS TYPES INSTEAD OF LISTING THEM ─────────────────────────
 * This script used to carry a hardcoded list of five types, each with an
 * `active == true` filter. Both choices lost data silently, and the script still
 * printed a confident total:
 *
 *   - `active == true` dropped 50 real documents — all 5 museumLocations (every
 *     one is active:false / isPast:true), 15 artists including all 17 name-only
 *     stubs, and 30 trashItems. Inactive does not mean disposable: it means the
 *     public site doesn't build a page for it. The document is still the only
 *     copy of that content.
 *   - The hardcoded list silently omitted every type added afterwards — partner,
 *     pressItem and trashInvoice, 31 more documents.
 *
 * A backup that quietly holds 81 fewer documents than the dataset is worse than
 * no backup, because it is trusted. So: discover the types, filter nothing, and
 * verify the result against a live count before claiming success.
 */
import { createClient } from '@sanity/client';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.join(__dirname, '..', 'sanity-backup');

const client = createClient({
  projectId: 't5nsm79o',
  dataset: 'production',
  apiVersion: '2026-03-20',
  token: process.env.SANITY_WRITE_TOKEN, // optional — dataset reads are public
  useCdn: false,                         // never a cached view of a backup
});

/**
 * Sanity's own bookkeeping — retention policy, schema manifest, UI groups. Not
 * content, not restorable, and regenerated by the platform. Everything else is
 * kept, including sanity.imageAsset / sanity.fileAsset: those documents hold the
 * asset URLs and metadata that image references resolve through, so a restore
 * without them would leave every image field dangling.
 */
const SKIP_PREFIX = 'system.';

const fileFor = (type) => type.replace(/[^a-zA-Z0-9]+/g, '-') + '.json';

async function run() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const exportedAt = new Date().toISOString();
  const counts = {};
  const problems = [];

  console.log(`Sanity backup — ${exportedAt}`);
  console.log(`Output: ${OUT_DIR}\n`);

  const types = (await client.fetch('array::unique(*[]._type)'))
    .filter((t) => !t.startsWith(SKIP_PREFIX))
    .sort();

  for (const type of types) {
    // No filter, and drafts included: a draft is unpublished work that exists
    // nowhere else, which is exactly what a backup is for.
    const docs = await client.fetch('*[_type == $type] | order(_id asc)', { type });
    const live = await client.fetch('count(*[_type == $type])', { type });

    const file = fileFor(type);
    fs.writeFileSync(path.join(OUT_DIR, file), JSON.stringify(docs, null, 2));
    counts[type] = docs.length;

    // The old script's failure mode was silence, so this one is loud.
    const ok = docs.length === live;
    if (!ok) problems.push(`${type}: wrote ${docs.length}, dataset has ${live}`);
    console.log(
      `  ${ok ? '✓' : '✗'} ${type.padEnd(24)} ${String(docs.length).padStart(5)} docs → ${file}` +
      (ok ? '' : `   MISMATCH, dataset has ${live}`)
    );
  }

  const total = Object.values(counts).reduce((a, b) => a + b, 0);
  const liveTotal = await client.fetch(
    `count(*[!(_type match "${SKIP_PREFIX}*")])`
  );
  if (total !== liveTotal) problems.push(`total: wrote ${total}, dataset has ${liveTotal}`);

  const manifest = {
    exportedAt,
    projectId: 't5nsm79o',
    dataset: 'production',
    types: types.length,
    total,
    counts,
    note:
      'Full dataset, no active/visibility filter, drafts included. system.* is ' +
      'excluded as platform bookkeeping. Verified against live counts at export.',
  };
  fs.writeFileSync(path.join(OUT_DIR, 'backup-manifest.json'), JSON.stringify(manifest, null, 2));

  console.log(`\n${types.length} types, ${total} documents backed up.`);
  console.log(`Manifest: sanity-backup/backup-manifest.json`);

  if (problems.length) {
    console.error(`\nBACKUP INCOMPLETE — do not rely on this snapshot:`);
    problems.forEach((p) => console.error(`  ✗ ${p}`));
    process.exit(1);
  }
  console.log('Verified: every type matches its live count.');
}

run().catch((err) => { console.error('Backup failed:', err); process.exit(1); });
